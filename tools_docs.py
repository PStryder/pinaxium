"""Generate docs/REFERENCE.md from what the server actually advertises over MCP (initialize, tools/list,
resources/list, resources/templates/list), so the reference can't drift from the code.

    uv run python tools_docs.py            # rewrite docs/REFERENCE.md
    uv run python tools_docs.py --check    # exit 1 if docs/REFERENCE.md is out of date (tests/test_docs.py)
"""

import asyncio
import os
import sys
import tempfile

from mcp.client.session import ClientSession
from mcp.client.stdio import StdioServerParameters, stdio_client

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "docs", "REFERENCE.md")
HINT_NAMES = {"readOnlyHint": "read-only", "destructiveHint": "destructive", "idempotentHint": "idempotent",
              "openWorldHint": "open-world"}


async def catalogue():
    # hermetic: throwaway config/state, an empty ComfyUI folder and a dead port, so the output is the same on
    # every machine (the catalogue doesn't depend on the install)
    tmp = tempfile.mkdtemp(prefix="pinaxium-docs-")
    env = {**os.environ, "PINAXIUM_CONFIG": os.path.join(tmp, "config.toml"), "PINAXIUM_COMFY_DIR": tmp,
           "PINAXIUM_STATE_DIR": os.path.join(tmp, "state"), "PINAXIUM_PORT": "1"}
    params = StdioServerParameters(command=sys.executable, args=["-m", "pinaxium.server"], cwd=HERE, env=env)
    async with stdio_client(params) as streams, ClientSession(*streams) as s:
        init = await s.initialize()
        tools = (await s.list_tools()).tools
        resources = [r for r in (await s.list_resources()).resources if not str(r.uri).startswith("pinaxium://images/")]
        templates = (await s.list_resource_templates()).resource_templates
        return init, tools, resources, templates


def _type(p: dict) -> str:
    if "$ref" in p:
        return p["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in p:
        parts = [_type(x) for x in p["anyOf"] if x.get("type") != "null"]
        return " \\| ".join(parts) + (" \\| null" if any(x.get("type") == "null" for x in p["anyOf"]) else "")
    if "enum" in p:
        return " \\| ".join(f"`{v}`" for v in p["enum"])
    t = p.get("type", "any")
    if t == "array":
        return f"array of {_type(p.get('items', {}))}"
    if t == "object" and "additionalProperties" in p:
        return "object"
    return t


def _fields(schema: dict) -> list[str]:
    rows = ["| Field | Type | Description |", "|---|---|---|"]
    for name, p in schema.get("properties", {}).items():
        rows.append(f"| `{name}` | {_type(p)} | {_cell(p.get('description', ''))} |")
    return rows


def _output(schema: dict) -> list[str]:
    out = ["", "Structured result (`structuredContent`; the same JSON is also sent as text):", ""] + _fields(schema)
    for name, sub in schema.get("$defs", {}).items():
        out += ["", f"`{name}`:", ""] + _fields(sub)
    return out


def _range(p: dict) -> str:
    for x in [p] + p.get("anyOf", []):
        lo, hi = x.get("minimum"), x.get("maximum")
        items = (x.get("minItems"), x.get("maxItems"))
        length = (x.get("minLength"), x.get("maxLength"))
        if lo is not None or hi is not None:
            return f"{'' if lo is None else lo}–{'' if hi is None else hi}"
        if any(v is not None for v in items):
            return f"{items[0] or 0}–{items[1] if items[1] is not None else '∞'} items"
        if length[0] and not length[1]:
            return "non-empty"
    return ""


def _cell(s: str) -> str:
    return " ".join(str(s).split()).replace("|", "\\|")


def render(init, tools, resources, templates) -> str:
    si = init.server_info
    out = [f"# {si.title or si.name} — MCP reference",
           "",
           f"<!-- generated by tools_docs.py from the live server; edit the code, then run `uv run python tools_docs.py` -->",
           "",
           f"Server `{si.name}` version {si.version}, protocol {init.protocol_version}.",
           "",
           "## Instructions sent to clients",
           "",
           "These are delivered to the client at connection time; agents see them as the server's usage guide.",
           "",
           "> " + "\n> ".join(init.instructions.rstrip().splitlines()),
           "",
           "## Tools",
           "",
           "| Tool | Title | Hints |",
           "|---|---|---|"]
    for t in tools:
        ann = t.annotations.model_dump(by_alias=True, exclude_none=True) if t.annotations else {}
        hints = ", ".join(v for k, v in HINT_NAMES.items() if ann.get(k)) or "—"
        out.append(f"| [`{t.name}`](#{t.name}) | {t.title} | {hints} |")
    for t in tools:
        d = t.model_dump(by_alias=True, exclude_none=True)
        out += ["", f"### {t.name}", "", f"**{t.title}**", "", d.get("description", "").strip(), ""]
        props = d["inputSchema"].get("properties", {})
        required = set(d["inputSchema"].get("required", []))
        if props:
            out += ["| Parameter | Type | Required | Default | Range | Description |", "|---|---|---|---|---|---|"]
            for name, p in props.items():
                default = "" if name in required else f"`{p.get('default')!r}`"
                out.append(f"| `{name}` | {_type(p)} | {'yes' if name in required else ''} | {default} | "
                           f"{_range(p)} | {_cell(p.get('description', ''))} |")
        else:
            out.append("No parameters.")
        if d.get("outputSchema"):
            out += _output(d["outputSchema"])
    out += ["", "## Resources", "", "| URI | Name | MIME type | Description |", "|---|---|---|---|"]
    for r in resources:
        out.append(f"| `{r.uri}` | {r.title or r.name} | {r.mime_type} | {_cell(r.description or '')} |")
    for t in templates:
        out.append(f"| `{t.uri_template}` (template) | {t.title or t.name} | {t.mime_type} | {_cell(t.description or '')} |")
    caps = init.capabilities.resources
    out += ["", f"Resource capabilities: subscribe = {str(caps.subscribe).lower()}, "
                f"listChanged = {str(caps.list_changed).lower()}. Saved images are listed individually by "
                "`resources/list` (newest 500) under `pinaxium://images/`.", ""]
    return "\n".join(out)


def generate() -> str:
    return render(*asyncio.run(catalogue()))


def main(argv) -> int:
    text = generate()
    if "--check" in argv:
        current = open(TARGET, encoding="utf-8").read() if os.path.isfile(TARGET) else ""
        if current != text:
            print("docs/REFERENCE.md is out of date: run `uv run python tools_docs.py`")
            return 1
        print("docs/REFERENCE.md is up to date")
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
